"""
The experiment: Prompt V1 against Prompt V2 over the same 20 cases.

Held constant across both arms: the policy file (verified by hash), the 20
questions, the answering model, temperature 0, the graders, and the rubric. The
prompt is the only thing that moves.

Grading is blind. Every response is stripped of its version label and the whole
pool is shuffled before grading, so a judge cannot know which arm it is marking
or infer it from position.

Three stages, run independently so one provider being down cannot corrupt or
block the others:

    python run_experiment.py answer                 freeze the 40 responses
    python run_experiment.py grade claude           add one judge's verdicts
    python run_experiment.py grade gemini           add the other's, later
    python run_experiment.py report                 summarise whatever exists

Answers are written once and never regenerated by a grading run, so adding a
second judge later cannot silently change what was judged.

Headline metric is the COUNT of responses containing an unsupported claim, not
the average score. A count is checkable; a fraction of a point on a
self-authored ten-point scale is not.
"""

import io
import json
import random
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import config
import pipeline

VERSIONS = ("v1", "v2")
SHUFFLE_SEED = 20260821  # fixed, so the blind ordering is reproducible
RESPONSES = "responses.json"


# --- stage 1: answer --------------------------------------------------------


def stage_answer():
    if not config.preflight(("anthropic",)):
        print("Aborting: answering provider unavailable. Nothing written.")
        return 2

    cases = config.load_json("dataset.json")["cases"]
    cases_by_id = {c["id"]: c for c in cases}
    jobs = [(c, v) for v in VERSIONS for c in cases]

    def work(job):
        c, v = job
        # Only the question string crosses into the answering layer.
        return {"case_id": c["id"], "version": v, "question": c["question"],
                "response": pipeline.run_prompt(c["question"], v)}

    print(f"Answering {len(jobs)} calls ({len(cases)} cases x {len(VERSIONS)} versions)...")
    with ThreadPoolExecutor(max_workers=6) as ex:
        records = list(ex.map(work, jobs))

    for r in records:
        r["code_grade"] = pipeline.code_grade(r["response"], cases_by_id[r["case_id"]])

    doc = {"meta": {"policy_hash": config.policy_hash(),
                    "answer_model": config.ANSWER_MODEL,
                    "answer_temperature": config.ANSWER_TEMPERATURE,
                    "n_cases": len(cases), "versions": list(VERSIONS)},
           "records": records}
    config.archive_existing(RESPONSES)
    io.open(config.RESULTS / RESPONSES, "w", encoding="utf-8").write(
        json.dumps(doc, indent=2, ensure_ascii=False))

    for v in VERSIONS:
        coded = [r for r in records if r["version"] == v and r["code_grade"]]
        print(f"  {v}: code grader {sum(1 for r in coded if r['code_grade']['passed'])}"
              f"/{len(coded)} passed")
    print(f"written -> results/{RESPONSES}  (policy hash {doc['meta']['policy_hash']})")
    return 0


# --- stage 2: grade ---------------------------------------------------------


def stage_grade(provider):
    prov_key = "anthropic" if provider == "claude" else "gemini"
    if not config.preflight((prov_key,)):
        print(f"Aborting: {provider} unavailable. Nothing written.")
        return 2

    path = config.RESULTS / RESPONSES
    if not path.exists():
        print(f"No results/{RESPONSES}. Run `python run_experiment.py answer` first.")
        return 2
    doc = json.load(io.open(path, encoding="utf-8"))
    records = doc["records"]

    # Blind: strip version, shuffle the pool, grade text only.
    pool = list(records)
    random.Random(SHUFFLE_SEED).shuffle(pool)

    def work(item):
        i, p = item
        return (i, pipeline.model_grade(p["response"], p["question"], provider))

    print(f"Grading {len(pool)} responses with {provider} (blind, shuffled)...")
    with ThreadPoolExecutor(max_workers=6) as ex:
        out = list(ex.map(work, list(enumerate(pool))))

    for i, g in out:
        pool[i][provider] = g

    errs = sum(1 for r in records if r.get(provider, {}).get("has_violation") is None)
    doc.setdefault("meta", {}).setdefault("graded_by", [])
    if provider not in doc["meta"]["graded_by"]:
        doc["meta"]["graded_by"].append(provider)
    doc["meta"][f"{provider}_model"] = (config.GRADER_CLAUDE if provider == "claude"
                                        else config.GRADER_GEMINI)
    doc["meta"][f"{provider}_no_verdict_errors"] = errs
    doc["meta"]["blind_grading"] = True
    doc["meta"]["shuffle_seed"] = SHUFFLE_SEED

    io.open(path, "w", encoding="utf-8").write(json.dumps(doc, indent=2, ensure_ascii=False))
    print(f"  {len(pool) - errs}/{len(pool)} verdicts returned, {errs} errors")
    print(f"updated -> results/{RESPONSES}")
    return 0


# --- stage 3: report --------------------------------------------------------


def summarise(records, version, providers):
    rs = [r for r in records if r["version"] == version]
    out = {"version": version, "n_cases": len(rs)}
    for prov in providers:
        judged = [r for r in rs if r.get(prov, {}).get("has_violation") is not None]
        flagged = [r for r in judged if r[prov]["has_violation"] is True]
        scores = [r[prov]["score"] for r in judged if isinstance(r[prov].get("score"), int)]
        out[prov] = {
            "responses_with_unsupported_claim": len(flagged),
            "of_judged": len(judged),
            "no_verdict_errors": len(rs) - len(judged),
            "total_unsupported_claims": sum(
                len(r[prov].get("unsupported_claims") or []) for r in judged),
            "avg_score": round(sum(scores) / len(scores), 2) if scores else None,
            "flagged_case_ids": sorted(r["case_id"] for r in flagged),
        }
    coded = [r for r in rs if r.get("code_grade")]
    out["code_grader"] = {
        "cases_with_assertions": len(coded),
        "passed": sum(1 for r in coded if r["code_grade"]["passed"]),
        "failed_case_ids": sorted(r["case_id"] for r in coded if not r["code_grade"]["passed"]),
    }
    return out


def stage_report():
    path = config.RESULTS / RESPONSES
    if not path.exists():
        print(f"No results/{RESPONSES}. Run the answer stage first.")
        return 2
    doc = json.load(io.open(path, encoding="utf-8"))
    records = doc["records"]
    providers = doc["meta"].get("graded_by", [])
    if not providers:
        print("No grades yet. Run `python run_experiment.py grade claude`.")
        return 2

    # Recompute the deterministic grades from the current dataset rather than
    # reusing what the answering stage stored. The code grader has no
    # randomness, so re-running it on frozen responses changes nothing except
    # to pick up a corrected assertion, and it applies to both arms equally.
    cases_by_id = {c["id"]: c for c in config.load_json("dataset.json")["cases"]}
    for r in records:
        r["code_grade"] = pipeline.code_grade(r["response"], cases_by_id[r["case_id"]])

    per = {v: summarise(records, v, providers) for v in VERSIONS}
    comparison = {"meta": doc["meta"], "v1": per["v1"], "v2": per["v2"], "headline": {}}
    for prov in providers:
        a, b = per["v1"][prov], per["v2"][prov]
        comparison["headline"][prov] = {
            "responses_with_unsupported_claim_v1": a["responses_with_unsupported_claim"],
            "responses_with_unsupported_claim_v2": b["responses_with_unsupported_claim"],
            "change": b["responses_with_unsupported_claim"] - a["responses_with_unsupported_claim"],
            "total_claims_v1": a["total_unsupported_claims"],
            "total_claims_v2": b["total_unsupported_claims"],
            "avg_score_v1": a["avg_score"], "avg_score_v2": b["avg_score"],
            "fixed_case_ids": sorted(set(a["flagged_case_ids"]) - set(b["flagged_case_ids"])),
            "broken_case_ids": sorted(set(b["flagged_case_ids"]) - set(a["flagged_case_ids"])),
        }

    # Agreement between judges, where both returned a verdict on the same response.
    if len(providers) > 1:
        pa, pb = providers[0], providers[1]
        both = [r for r in records
                if r.get(pa, {}).get("has_violation") is not None
                and r.get(pb, {}).get("has_violation") is not None]
        agree = sum(1 for r in both if r[pa]["has_violation"] == r[pb]["has_violation"])
        comparison["judge_agreement"] = {
            "providers": [pa, pb], "agree": agree, "of": len(both),
            "rate": round(agree / len(both), 3) if both else None,
            "disagreed_on": [{"case_id": r["case_id"], "version": r["version"]}
                             for r in both if r[pa]["has_violation"] != r[pb]["has_violation"]],
        }

    comparison["code_grader"] = {
        "of": per["v1"]["code_grader"]["cases_with_assertions"],
        "v1_passed": per["v1"]["code_grader"]["passed"],
        "v2_passed": per["v2"]["code_grader"]["passed"],
        "v1_failed_case_ids": per["v1"]["code_grader"]["failed_case_ids"],
        "v2_failed_case_ids": per["v2"]["code_grader"]["failed_case_ids"],
    }

    config.archive_existing("comparison.json")
    io.open(config.RESULTS / "comparison.json", "w", encoding="utf-8").write(
        json.dumps(comparison, indent=2, ensure_ascii=False))

    print("\n" + "=" * 72)
    print(f"policy hash {doc['meta']['policy_hash']}   identical across both arms")
    print(f"answering   {doc['meta']['answer_model']} at temperature "
          f"{doc['meta']['answer_temperature']}")
    print(f"judges      {', '.join(providers)}   blind, shuffled")
    for prov in providers:
        h = comparison["headline"][prov]
        print(f"\n{prov.upper()} judge")
        print(f"  responses with an unsupported claim   V1 {h['responses_with_unsupported_claim_v1']:>2}"
              f"  ->  V2 {h['responses_with_unsupported_claim_v2']:>2}   of 20")
        print(f"  total unsupported claims              V1 {h['total_claims_v1']:>2}"
              f"  ->  V2 {h['total_claims_v2']:>2}")
        print(f"  average score (supporting only)       V1 {h['avg_score_v1']}"
              f"  ->  V2 {h['avg_score_v2']}")
        if h["fixed_case_ids"]:
            print(f"  fixed by V2:  {', '.join(h['fixed_case_ids'])}")
        if h["broken_case_ids"]:
            print(f"  broken by V2: {', '.join(h['broken_case_ids'])}")
    if "judge_agreement" in comparison:
        ja = comparison["judge_agreement"]
        print(f"\njudge agreement {ja['agree']}/{ja['of']}"
              f" = {ja['rate']:.0%}" if ja["of"] else "\njudge agreement: n/a")
    c = comparison["code_grader"]
    print(f"\ncode grader ({c['of']} cases)   V1 {c['v1_passed']}/{c['of']}"
          f"  ->  V2 {c['v2_passed']}/{c['of']}")
    print("\nwritten -> results/comparison.json")
    return 0


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 2
    cmd = args[0]
    if cmd == "answer":
        return stage_answer()
    if cmd == "grade":
        if len(args) < 2 or args[1] not in ("claude", "gemini"):
            print("usage: run_experiment.py grade [claude|gemini]")
            return 2
        return stage_grade(args[1])
    if cmd == "report":
        return stage_report()
    print(f"unknown stage {cmd!r}")
    return 2


if __name__ == "__main__":
    sys.exit(main())
